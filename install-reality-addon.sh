#!/bin/sh
# WEB PANEL ONLINE 3.0 - additive REALITY/XTLS Vision patch (test branch only).
# Usage: sudo /tmp/wpo-reality-addon
# DOES NOT run install-panel.sh, update.sh, node-install.sh or reset the panel.
set -eu
umask 077

REPOSITORY='TonyMaster14/web-panel-online'
BASE_REF='e43b4941a0ef28c202952cc4b890b7afce13aeb1'
FEATURE_REF='e81d81a98262ae0e1998694c570ab6043374a41d'
APP='/opt/tproxy-panel'
STATE='/var/lib/tproxy-panel'
SVC='tproxy-panel.service'
XRAY='/opt/web-panel-proxy/xray/xray'
MUX='/etc/systemd/system/web-panel-proxy-tls-mux.service'
WORK=''
BACKUP=''
CHANGED=0

log() { printf '\n[WPO REALITY] %s\n' "$*"; }
die() { printf '\n[WPO REALITY] ОШИБКА: %s\n' "$*" >&2; exit 1; }

cleanup() {
    status=$?
    trap - EXIT INT TERM
    if [ "$status" -ne 0 ] && [ "$CHANGED" -eq 1 ] && [ -n "$BACKUP" ]; then
        printf '\n[WPO REALITY] Ошибка установки, возвращаю предыдущие файлы...\n' >&2
        if [ -s "$BACKUP/new-paths" ]; then
            while IFS= read -r name; do [ -n "$name" ] && rm -f -- "$name"; done < "$BACKUP/new-paths"
        fi
        if [ -s "$BACKUP/state.tar" ]; then tar -C / -xpf "$BACKUP/state.tar" || true; fi
        systemctl daemon-reload || true
        systemctl restart "$SVC" || true
        if systemctl is-active --quiet web-panel-proxy-tls-mux.service; then
            systemctl restart web-panel-proxy-tls-mux.service || true
        fi
        log "Откат выполнен. Резервная копия: $BACKUP"
    fi
    if [ -n "$WORK" ]; then rm -rf -- "$WORK"; fi
    exit "$status"
}
trap cleanup EXIT
trap 'exit 130' INT TERM

[ "$(id -u)" -eq 0 ] || die 'Запустите установщик через sudo.'
for tool in curl git python3 tar systemctl; do
    command -v "$tool" >/dev/null 2>&1 || die "Необходима команда: $tool"
done
for file in "$APP/panel.py" "$APP/wpp_ui.py" "$APP/wpp_connections.py" "$APP/wpp_routing.py" "$APP/wpp_nodes.py" "$XRAY"; do
    [ -s "$file" ] || die "Нужен установленный WPO 3.0, отсутствует $file"
done
systemctl is-active --quiet "$SVC" || die 'Панель не запущена: сначала устраните основную неисправность.'
grep -Fq 'wpo-node-spinner-center-v26' "$APP/wpp_ui.py" ||
    die 'Не найден Nodes Lab v26. Установщик не будет менять другую версию панели.'
[ ! -e "$APP/wpp_reality.py" ] ||
    die 'Модуль REALITY уже существует. Для обновления нужен отдельный сценарий, перезапись запрещена.'
[ ! -e "$MUX" ] ||
    grep -Fq 'WEB PANEL ONLINE TCP/443 TLS SNI passthrough' "$MUX" ||
    die 'На сервере есть посторонняя служба маршрутизации TLS/443 — не перезаписываю.'

WORK="$(mktemp -d /tmp/wpo-reality-addon.XXXXXXXX)"
mkdir -p "$WORK/base" "$WORK/feature" "$WORK/stage"
download() {
    ref="$1"; file="$2"; dest="$3"
    url="https://raw.githubusercontent.com/$REPOSITORY/$ref/$file"
    curl -4fLsS --connect-timeout 15 --max-time 120 --retry 2 "$url" -o "$dest" ||
        die "Не удалось скачать $file из $ref"
    [ -s "$dest" ] || die "Получен пустой $file"
}

log '1/6 · Загружаю только исходники дополнения и базовые эталоны'
for file in wpp_connections.py wpp_routing.py wpp_ui.py wpp_nodes.py install-panel.sh; do
    download "$BASE_REF" "$file" "$WORK/base/$file"
    download "$FEATURE_REF" "$file" "$WORK/feature/$file"
done
download "$FEATURE_REF" wpp_reality.py "$WORK/stage/wpp_reality.py"
download "$FEATURE_REF" node-install.sh "$WORK/feature/node-install.sh"

# panel.py is generated by install-panel.sh, but a full panel install must NOT run.
python3 - "$WORK" <<'PY_EXTRACT'
from pathlib import Path
import sys
root=Path(sys.argv[1])
marker='cat > "$APP_FILE" <<' + "'PY'\n"
for version in ('base','feature'):
    text=(root/version/'install-panel.sh').read_text(encoding='utf-8')
    if text.count(marker)!=1: raise SystemExit('Несовместимый шаблон создания panel.py: '+version)
    content=text.split(marker,1)[1].split('\nPY\n',1)
    if len(content)!=2 or not content[0].startswith('#!/usr/bin/env python3'):
        raise SystemExit('Не удалось выделить исходник panel.py: '+version)
    (root/version/'panel.py').write_text(content[0]+'\n',encoding='utf-8')
PY_EXTRACT

log '2/6 · Объединяю изменения с установленным Nodes Lab v26'
for file in panel.py wpp_connections.py wpp_routing.py wpp_ui.py wpp_nodes.py; do
    if ! git merge-file -p "$APP/$file" "$WORK/base/$file" "$WORK/feature/$file" \
          > "$WORK/stage/$file"; then
        die "Конфликт версии в $file. Файлы работающей панели не изменены."
    fi
done

# Execute ONLY the existing isolated node-SNI patch, not the 3500-line node installer.
python3 - "$WORK" <<'PY_PATCH'
from pathlib import Path
import re,sys,subprocess
root=Path(sys.argv[1]); source=(root/'feature/node-install.sh').read_text(encoding='utf-8')
pattern=r'(?m)^    python3 - "\$UI" "\$PANEL" <<\x27PY_NODE_REALITY_SNI\x27\n(.*?)\nPY_NODE_REALITY_SNI\n'
matches=re.findall(pattern,source,re.S)
if len(matches)!=1: raise SystemExit('Версия Node SNI patch несовместима; установка прервана')
patch=root/'node-sni-patch.py'
patch.write_text(matches[0]+'\n',encoding='utf-8')
cmd=[sys.executable,str(patch),str(root/'stage/wpp_ui.py'),str(root/'stage/panel.py')]
subprocess.run(cmd,check=True,timeout=45)
PY_PATCH

log '3/6 · Проверяю Python, Firefox, SNI и формат Xray'
python3 -m py_compile "$WORK/stage/"*.py
PYTHONPATH="$WORK/stage" python3 - "$WORK" "$XRAY" <<'PY_TEST'
from pathlib import Path
import json,sys,subprocess,tempfile
import wpp_connections as connections
import wpp_reality as reality
root=Path(sys.argv[1]); xray=sys.argv[2]
connection=next(item for item in connections.defaults() if item['id']=='vless-reality-primary')
assert connection['config']['fingerprint']=='firefox'
assert connection['config']['sni']=='www.microsoft.com'
assert {'www.yahoo.com','www.nvidia.com'}.issubset(set(v for v,_ in reality.SNI_CANDIDATES))
profile=reality.ensure_profile(connection['id'],xray,str(root/'test-reality-secrets.json'))
client_id='8b888888-8888-4888-8888-888888888888'
client={'id':client_id,'email':'test','level':0,'flow':'xtls-rprx-vision'}
inbound=reality.server_inbound(connection,[client],profile)
cfg={'log':{'loglevel':'warning'},'inbounds':[inbound],'outbounds':[{'protocol':'freedom'}]}
config=root/'test-xray.json'; config.write_text(json.dumps(cfg),encoding='utf-8')
link=reality.client_link(client_id,'198.51.100.1','WPO test',connection,profile)
assert 'fp=firefox' in link and 'flow=xtls-rprx-vision' in link
run=subprocess.run([xray,'run','-test','-config',str(config)],capture_output=True,text=True,timeout=45)
if run.returncode: raise SystemExit('Xray не принял тестовый REALITY config: '+(run.stderr or run.stdout)[-1200:])
print('OK: Xray config valid, Mozilla Firefox, Vision, Microsoft + Yahoo + NVIDIA')
PY_TEST

# HAProxy is only required when a REALITY client uses shared TCP/443.
if ! command -v haproxy >/dev/null 2>&1; then
    log 'Устанавливаю HAProxy как отдельную зависимость (Caddy пока не трогаю)'
    export DEBIAN_FRONTEND=noninteractive
    apt-get -o Acquire::ForceIPv4=true -o DPkg::Lock::Timeout=600 update
    apt-get -o Acquire::ForceIPv4=true -o DPkg::Lock::Timeout=600 install -y --no-install-recommends haproxy
fi
[ -x /usr/sbin/haproxy ] || die 'HAProxy не установлен.'
[ -f /etc/caddy/Caddyfile ] || die 'Нет Caddyfile — безопасность HTTPS не подтверждена.'

log '4/6 · Делаю постоянную резервную копию только затрагиваемых файлов'
BACKUP="$STATE/wpo-reality-addon-backup-$(date -u +%Y%m%dT%H%M%SZ)-$$"
mkdir -p "$BACKUP"
chmod 0700 "$BACKUP"
: > "$BACKUP/files"
: > "$BACKUP/new-paths"
for file in \
    "$APP/panel.py" "$APP/wpp_connections.py" "$APP/wpp_routing.py" \
    "$APP/wpp_ui.py" "$APP/wpp_nodes.py" "$APP/wpp_reality.py" \
    "$MUX" /etc/web-proxy-panel/connections.json \
    /etc/web-proxy-panel/reality-profiles.json \
    /etc/web-proxy-panel/tls-mux.cfg \
    /etc/caddy/Caddyfile /etc/web-panel-proxy-xray/config.json
do
    if [ -e "$file" ]; then
        printf '%s\n' "$file" | sed 's@^/@@' >> "$BACKUP/files"
    else
        printf '%s\n' "$file" >> "$BACKUP/new-paths"
    fi
done
tar -C / -cpf "$BACKUP/state.tar" -T "$BACKUP/files"
chmod 0600 "$BACKUP/state.tar"
printf 'Test source SHA: %s\nBase SHA: %s\nCreated UTC: %s\n' "$FEATURE_REF" "$BASE_REF" "$(date -u +%FT%TZ)" > "$BACKUP/INFO.txt"

log '5/6 · Устанавливаю дополнение без полного обновления WPO'
CHANGED=1
for file in panel.py wpp_connections.py wpp_routing.py wpp_ui.py wpp_nodes.py wpp_reality.py; do
    install -m 0644 "$WORK/stage/$file" "$APP/$file"
done
chmod 0755 "$APP/panel.py"
cat > "$MUX" <<'WPO_MUX_SERVICE'
[Unit]
Description=WEB PANEL ONLINE TCP/443 TLS SNI passthrough (Caddy + REALITY)
After=network-online.target caddy.service web-panel-proxy-xray.service
Wants=network-online.target caddy.service web-panel-proxy-xray.service

[Service]
Type=simple
ExecStart=/usr/sbin/haproxy -db -f /etc/web-proxy-panel/tls-mux.cfg
ExecStartPre=/usr/sbin/haproxy -c -f /etc/web-proxy-panel/tls-mux.cfg
Restart=on-failure
RestartSec=2
LimitNOFILE=65536
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
WPO_MUX_SERVICE
chmod 0644 "$MUX"
systemctl daemon-reload
systemctl restart "$SVC"
systemctl is-active --quiet "$SVC" || die 'После патча панель не запустилась.'
grep -Fq '# wpo-node-reality-sni-settings' "$APP/wpp_ui.py" ||
    die 'В установленном редакторе нод нет поля SNI.'
grep -Fq 'xtls-rprx-vision' "$APP/panel.py" ||
    die 'REALITY Vision не встроен в контроллер.'
grep -Fq 'Mozilla Firefox' "$APP/wpp_ui.py" ||
    die 'В редакторе подключения не закреплён Firefox.'

log '6/6 · Финальная проверка без переключения порта 443'
systemctl is-active --quiet caddy.service || die 'Caddy не активен после установки.'
systemctl is-active --quiet "$SVC" || die 'WPO не активна после установки.'
CHANGED=0
log '✓ REALITY дополнение установлено. Порт 443 пока продолжает обслуживать Caddy.'
log '✓ Раздел Подключения: новый VLESS REALITY; раздел Ноды: SNI по карандашику.'
log '✓ Приватные ключи REALITY не создавались в рабочих каталогах до добавления клиента.'
log "✓ Бэкап и файлы отката: $BACKUP"
log '✓ main GitHub не изменён. Создайте тестового клиента с новым серверным подключением.'
